"""The qualification set on disk: its layout, its complexes, the boxes of config/, and cloning it from git.

Layout of a set root, one directory per complex and one folder per role in it:

    <pdb>/receptors/<pdb>.in       receptor topology (more receptors there make an ensemble)
    <pdb>/ligands/<pdb>_ligand.top ligand topology, the crystal pose
    <pdb>/cofactors/*.top          optional, one topology per cofactor, with the matching .pdb record
    config/<pdb>.toml              the box of the complex, generated by grid_toml_generator.py (not committed)
    index/affinity.csv             the affinities of the set

The folder names are the ones DockThor knows: given the complex directory (`--receptor <pdb>`) or its receptors
folder (`--receptor <pdb>/receptors`), it docks into every receptor there, each with the cofactors of
<pdb>/cofactors/.
"""

import re
import shlex
import subprocess
import sys
import tomllib
from pathlib import Path

from coreset.molecules import ligand_name, ligand_suffix


def git(*command: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    print("    $ git " + shlex.join(command), flush=True)
    return subprocess.run(["git", "-c", "advice.detachedHead=false", *command], cwd=cwd)


def repo_name(url: str) -> str:
    """https://github.com/org/set.git, git@github.com:org/set.git or /path/set -> set"""
    return re.split(r"[/:]", url.rstrip("/"))[-1].removesuffix(".git")


def clone_dataset(args) -> Path:
    """Clone (or reuse) the repository of --git-url and return the set root inside it."""
    clone_dir = (args.clone_dir or Path(repo_name(args.git_url))).expanduser().resolve()
    if (clone_dir / ".git").is_dir():
        print(f"Using the existing clone {clone_dir}")
        if args.git_update:
            ref = args.git_ref or "HEAD"
            if (
                git("fetch", "--depth", "1", "origin", ref, cwd=clone_dir).returncode != 0
                or git("checkout", "--detach", "FETCH_HEAD", cwd=clone_dir).returncode != 0
            ):
                sys.exit(f"[error] could not update {clone_dir} to {ref}")
    elif clone_dir.exists() and any(clone_dir.iterdir()):
        sys.exit(f"[error] {clone_dir} exists and is not a git clone; choose another --clone-dir")
    else:
        print(f"Cloning {args.git_url} into {clone_dir}")
        branch = ["--branch", args.git_ref] if args.git_ref else []
        if git("clone", "--depth", "1", *branch, args.git_url, str(clone_dir)).returncode != 0:
            if not args.git_ref:
                sys.exit(f"[error] could not clone {args.git_url}")
            # --branch takes only branches and tags: a commit needs a full clone and a checkout.
            if clone_dir.exists() and any(clone_dir.iterdir()):
                sys.exit(f"[error] could not clone {args.git_url}; {clone_dir} was left behind, remove it")
            if (
                git("clone", args.git_url, str(clone_dir)).returncode != 0
                or git("checkout", "--detach", args.git_ref, cwd=clone_dir).returncode != 0
            ):
                sys.exit(f"[error] could not clone {args.git_url} at {args.git_ref}")
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=clone_dir, capture_output=True, text=True).stdout.strip()
    print(f"Dataset commit: {commit}")
    return clone_dir / args.git_subdir if args.git_subdir else clone_dir


def infer_dataset(toml_dir: Path) -> Path | None:
    """The set root of a TOML folder: the first of toml_dir and its parents where the ligand and receptor of a TOML
    exist (paths relative to the set root), or that holds them (absolute paths)."""
    for toml_path in sorted(toml_dir.glob("*.toml")):
        try:
            config = tomllib.loads(toml_path.read_text())
        except (OSError, tomllib.TOMLDecodeError):
            continue
        if "ligand" not in config or "receptor" not in config:
            continue
        ligand = Path(config["ligand"])
        receptor = Path(config["receptor"])
        for root in (toml_dir, *toml_dir.parents):
            # Absolute paths (grid_toml_generator.py) exist from anywhere: the root is the first folder holding them.
            if ligand.is_absolute() and not ligand.is_relative_to(root):
                continue
            if (root / ligand).exists() and (root / receptor).exists():
                return root
        return None
    return None


#: The folders of a complex directory, one per role (DockThor's own names for them).
RECEPTORS_DIR = "receptors"
#: The index folder of a set: index/affinity.csv, the measured affinities (coreset/affinity.py).
INDEX_DIR = "index"
#: Inside receptors/: the charged PDB DockTScore reads (-p), which DockThor never looks at (it reads the .in, and
#: .pdb is not one of its receptor extensions).
PREP_DIR = "prep"
LIGANDS_DIR = "ligands"
COFACTORS_DIR = "cofactors"
LIGAND_TAG = "_ligand"  # 10gs_ligand.top is the ligand of complex 10gs


def receptor_path(pdb: str) -> Path:
    """The receptor topology of a complex, relative to the set root."""
    return Path(pdb) / RECEPTORS_DIR / f"{pdb}.in"


def prep_path(pdb: str) -> Path:
    """The charged PDB of a complex (occupancy = charge, B-factor = MMFF type), relative to the set root: what
    DockTScore reads as its receptor, written by PDBThorBox beside the .in topology."""
    return Path(pdb) / RECEPTORS_DIR / PREP_DIR / f"{pdb}_prep.pdb"


def ligand_path(pdb: str) -> Path:
    """The ligand topology of a complex, relative to the set root."""
    return Path(pdb) / LIGANDS_DIR / f"{pdb}{LIGAND_TAG}.top"


def cofactors_dir(root: Path, pdb: str) -> Path | None:
    """<pdb>/cofactors (relative to root, as written in a TOML) when it holds cofactor topologies, else None."""
    cofactors = Path(pdb) / COFACTORS_DIR
    return cofactors if any((root / cofactors).glob("*.top")) else None


def is_complex_dir(directory: Path) -> bool:
    """A directory holding the ligand of the complex it is named after: ligands/<pdb>_ligand in a DockThor format."""
    name = directory.name + LIGAND_TAG
    ligands = directory / LIGANDS_DIR
    return ligands.is_dir() and any(
        ligand_suffix(f) is not None and ligand_name(f) == name for f in ligands.iterdir() if f.is_file()
    )


def complex_dirs(root: Path) -> list[str]:
    """The complexes of a set: the directories of its root holding a <pdb>/ligands/<pdb>_ligand topology."""
    return sorted(d.name for d in root.iterdir() if is_complex_dir(d))
